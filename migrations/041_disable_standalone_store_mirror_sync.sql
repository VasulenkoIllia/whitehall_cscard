-- Migration 041: вимкнути осиротілу крон-задачу store_mirror_sync
--
-- Знімок магазину став кроком ① пайплайну ще в березні (коміт 9517dbc,
-- "add mirror sync to update pipeline"), і тоді ж задачу прибрали з UI з
-- поміткою "now a step inside update_pipeline". Але рядок у cron_settings
-- лишився увімкненим, і задача продовжила працювати кожні 2 години наосліп:
-- у коді дефолт false, в env не задана, в інтерфейсі не показана.
--
-- Наслідок — о 00:00, 06:00, 12:00 і 18:00 вона стартувала в один тік із
-- update_pipeline. За 7 днів спостережень 18 із 25 таких рубежів втрачено:
-- або два знімки взаємно знищували store_mirror (242 613 рядків → 613, після
-- чого store_import мовчки не відправляв нічого), або самостійна задача
-- забирала лок і пайплайн скасовувався цілком.
--
-- Код більше не реєструє цю задачу в планувальнику, а ALLOWED_TASK_NAMES її
-- ігнорує, тож рядок і так не застосовується. Вимикаємо його явно, щоб стан
-- у базі не суперечив коду і щоб відкат коду не повернув поломку.
--
-- Ручний запуск знімка з вкладки "Ручне керування" не зачіпається.
--
-- Ідемпотентно: UPDATE відфільтрований по is_enabled.

UPDATE cron_settings
   SET is_enabled = FALSE,
       updated_at = NOW()
 WHERE name = 'store_mirror_sync'
   AND is_enabled;
